-- SQL Script to Enable Persistent Manual Vendor Linking in Supabase
-- Paste this script into your Supabase SQL Editor (https://supabase.com -> Project -> SQL Editor -> New Query) and click Run

-- 1. Optional direct vendor_account column on beneficiaries
ALTER TABLE beneficiaries ADD COLUMN IF NOT EXISTS vendor_account text;
CREATE INDEX IF NOT EXISTS idx_beneficiaries_vendor_account ON beneficiaries(vendor_account);

-- 2. Dedicated Many-to-Many Vendor Links table (supports multiple bank accounts per vendor and manual overrides)
CREATE TABLE IF NOT EXISTS vendor_links (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vendor_account text NOT NULL,
    vendor_name text,
    ben_id bigint,
    ben_name text,
    account_number text NOT NULL,
    status text NOT NULL DEFAULT 'linked', -- 'linked' | 'unlinked' | 'rejected_review'
    method text DEFAULT 'manual',
    created_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL,
    CONSTRAINT unique_vendor_bank_link UNIQUE (vendor_account, account_number)
);

CREATE INDEX IF NOT EXISTS idx_vendor_links_va ON vendor_links(vendor_account);
CREATE INDEX IF NOT EXISTS idx_vendor_links_acc ON vendor_links(account_number);
CREATE INDEX IF NOT EXISTS idx_vendor_links_ben_id ON vendor_links(ben_id);

ALTER TABLE vendor_links DISABLE ROW LEVEL SECURITY;
GRANT ALL PRIVILEGES ON TABLE vendor_links TO anon, authenticated, service_role;
