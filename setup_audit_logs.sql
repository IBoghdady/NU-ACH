-- SQL Script to Create Audit Logs Table for Nile University ACH Portal
-- Paste this script into your Supabase SQL Editor (https://supabase.com -> Project -> SQL Editor -> New Query) and click Run

create table if not exists audit_logs (
    id bigint generated by default as identity primary key,
    user_email text,
    action text not null,
    category text not null,
    details text not null,
    metadata jsonb default '{}'::jsonb,
    ip_address text,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Performance indexes for querying audit trails
create index if not exists idx_audit_logs_created_at on audit_logs(created_at desc);
create index if not exists idx_audit_logs_user_email on audit_logs(user_email);
create index if not exists idx_audit_logs_category on audit_logs(category);

-- Disable Row Level Security so anon/authenticated can log actions
alter table audit_logs disable row level security;
grant all privileges on table audit_logs to anon, authenticated, service_role;
